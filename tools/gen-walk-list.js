// ============================================================
// tools/gen-walk-list.js — the in-game checklist for real coordinates
//
//   node tools/gen-walk-list.js > docs/WALK-LIST.md
//
// Lists every coordinate the maps and the game read — city borders,
// districts and parks, every road's points, every pin — with the
// placeholder it has now and the file it lives in. Walk it in game
// with /mark, paste the numbers in, then regenerate.
// ============================================================

const B = `${__dirname}/../js-snippets/`;
const places     = require(`${B}places.js`);
const cities     = require(`${B}cities.js`);
const spawns     = require(`${B}spawns.js`);
const shops      = require(`${B}shops.js`);
const fuel       = require(`${B}fuel.js`);
const medical    = require(`${B}medical.js`);
const jobs       = require(`${B}jobs.js`);
const police     = require(`${B}police.js`);
const houses     = require(`${B}houses.js`);
const impound    = require(`${B}impound.js`);
const appearance = require(`${B}appearance.js`);
const drugs      = require(`${B}drugs.js`);

const CODE = { chicago: "312 Chicago", geepee: "770 GeePee", atlanta: "1017 Atlanta" };
const ORDER = ["atlanta", "geepee", "chicago"];
const xy = (p) => `${p.x}, ${p.y}${p.z !== undefined ? `, ${p.z}` : ""}`;
const L = [];
const box = "- [ ]";

L.push("# Walk list — real coordinates for the maps and the game");
L.push("");
L.push("_Generated by `node tools/gen-walk-list.js > docs/WALK-LIST.md` from `js-snippets`. Don't edit by hand: fix the data, then regenerate._");
L.push("");
L.push("Every number below is a **placeholder** (a first guess, not a walked spot). Walk each one in game,");
L.push("capture the real position, and paste it into the file named next to it. When the list is done, the");
L.push("game's naming (`/whereami`, dispatch, the HUD), the atlas and the big map all line up.");
L.push("");
L.push("## How to capture");
L.push("");
L.push("1. Start the server with the `fourtune` resource (see `docs/NEXT-ON-PC.md`).");
L.push("2. Stand on the spot. For a **pin**, stand where the player should interact (the counter, the pump, the door).");
L.push("   For a **road**, stand on the centre line.");
L.push("3. Type `/mark <name>`. It replies with the position ready to paste, for example:");
L.push("   `MARK Alder Street bend: { x: -269.4, y: -955.3, z: 31.2 }  (atlanta)`");
L.push("4. Screenshot the chat or copy the line, and tick the box here.");
L.push("5. `/whereami` shows which road, park or district the game thinks you're in, which is a quick check once a section is pasted in.");
L.push("");
L.push("### Roads: what to mark");
L.push("");
L.push("- Drive each road **start to end** and `/mark` the start, **every real bend or junction**, and the end.");
L.push("  2 points for a straight road; add one wherever the road turns more than a little.");
L.push("- Where two roads meet, mark the **same spot** for both, so they join on the map.");
L.push("- `kind` stays as it is unless the road is clearly bigger or smaller than listed (highway, arterial, street, backroad).");
L.push("- Ring roads (The Perimeter, Knot Loop): mark around the loop and repeat the first point at the end to close it.");
L.push("");
L.push("### Zones: what to mark");
L.push("");
L.push("- Districts and parks are circles: mark the **centre**, then walk to the edge and mark again.");
L.push("  The radius is the distance between the two (or just estimate it in game units: about a metre each).");
L.push("");
L.push("## When the list is done");
L.push("");
L.push("```");
L.push("node --test js-snippets/game.test.js             # still green");
L.push("node tools/gen-world-data.js > world/data.lua    # the Lua world layer");
L.push("node tools/gen-map.js > docs/city-map.html       # the atlas");
L.push("node tools/gen-map-detail-layer.js               # the big map's roads, pins and legend");
L.push("node tools/gen-walk-list.js > docs/WALK-LIST.md  # this list, with the new numbers");
L.push("```");
L.push("");
L.push("Then tell Claude the coordinates are walked: the big map's 13 hand-drawn main roads get replaced by the");
L.push("walked ones, and the towers, stations, cars and road wear get re-placed against them.");
L.push("");

// ---- borders
L.push("## 1. City borders — `js-snippets/cities.js`");
L.push("");
L.push("Drive north across each line and mark where the city should change. Only the **y** matters.");
L.push("");
L.push(`${box} Atlanta → GeePee: \`GEEPEE_STARTS_AT_Y = ${cities.GEEPEE_STARTS_AT_Y}\``);
L.push(`${box} GeePee → Chicago: \`CHICAGO_STARTS_AT_Y = ${cities.CHICAGO_STARTS_AT_Y}\``);
L.push("");

// ---- zones
L.push("## 2. Districts and parks — `js-snippets/places.js` (`ZONES`)");
L.push("");
for (const city of ORDER) {
    const zs = places.ZONES.filter((z) => z.city === city);
    if (!zs.length) continue;
    L.push(`### ${CODE[city]}`);
    L.push("");
    for (const z of zs) L.push(`${box} **${z.name}** (${z.kind}): centre \`${xy(z.center)}\`, radius \`${z.radius}\``);
    L.push("");
}

// ---- roads
const KIND_ORDER = ["highway", "arterial", "street", "backroad"];
L.push("## 3. Roads — `js-snippets/places.js` (`ROAD_DEFS`)");
L.push("");
L.push(`${places.ROADS.length} roads. Each line shows the points it has now, in order from start to end.`);
L.push("");
for (const city of ORDER) {
    const rs = places.ROADS.filter((r) => cities.cityAt(r.points[0]) === city)
        .sort((a, b) => KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind));
    L.push(`### ${CODE[city]} — ${rs.length} roads`);
    L.push("");
    for (const r of rs) {
        const pts = r.points.map((p) => `(${p.x}, ${p.y})`).join(" → ");
        L.push(`${box} **${r.name}** · ${r.kind} · ${r.points.length} points: ${pts}`);
    }
    L.push("");
}

// ---- pins
const pins = [];
const add = (file, kind, label, pos) => pins.push({ file, kind, label, pos, city: cities.cityAt(pos) });
for (const list of Object.values(spawns.SPAWNS)) for (const s of list) add("spawns.js (SPAWNS, also set heading)", "Spawn", s.label, s.pos);
for (const s of Object.values(shops.SHOPS)) add("shops.js (SHOPS)", s.goldItems ? "Gun shop" : "Shop", s.label, s.pos);
for (const g of fuel.GAS_STATIONS) add("fuel.js (GAS_STATIONS)", "Fuel", g.label, g.pos);
for (const list of Object.values(medical.HOSPITALS)) for (const h of list) add("medical.js (HOSPITALS)", "Hospital", h.label, h.pos);
for (const job of Object.values(jobs.JOBS)) for (const pos of Object.values(job.stations || {})) add("jobs.js (stations)", "Duty station", job.label, pos);
add("police.js (JAIL.cell)", "Jail", "County Lockup cell", police.JAIL.cell);
for (const h of Object.values(houses.HOUSES)) add("houses.js (HOUSES)", "Housing", h.label, h.pos);
for (const l of impound.LOTS) add("impound.js (LOTS)", "Impound", l.label, l.pos);
for (const s of appearance.SHOPS) add("appearance.js (SHOPS)", "Clothes", s.label, s.pos);
for (const s of drugs.SUPPLY_SPOTS) add("drugs.js (SUPPLY_SPOTS)", "Supply drop", s.label, s.pos);

L.push("## 4. Places players use — pins");
L.push("");
L.push(`${pins.length} spots. Stand where the player interacts.`);
L.push("");
for (const city of ORDER) {
    const ps = pins.filter((p) => p.city === city);
    L.push(`### ${CODE[city]} — ${ps.length} spots`);
    L.push("");
    for (const p of ps) L.push(`${box} **${p.label}** · ${p.kind} · now \`${xy(p.pos)}\` · \`js-snippets/${p.file}\``);
    L.push("");
}

// ---- not in the data yet
L.push("## 5. On the maps but not in the game data yet");
L.push("");
L.push("These were drawn on the maps without game positions. Mark them and say where they should go,");
L.push("and they'll be added to the data so the game knows about them too.");
L.push("");
for (const s of [
    "Glizzys-2-Go job station(s): where `/apply glizzys` should work (`jobs.js`, glizzys `stations`)",
    "Dockhand job station: the harbor spot where `/apply dockhand` should work (`jobs.js`, dockhand `stations`)",
    "Highfield Park Drive and its harbor spur (only on the big map)",
    "The 1017 Harbor and the 312 Port: a point on each quay",
    "The airport: the terminal door and the runway's two ends",
]) L.push(`${box} ${s}`);
L.push("");
L.push(`_Totals: 2 borders, ${places.ZONES.length} zones, ${places.ROADS.length} roads (${places.ROADS.reduce((n, r) => n + r.points.length, 0)} points), ${pins.length} pins._`);

process.stdout.write(L.join("\n") + "\n");
