#!/usr/bin/env node
// ============================================================
// tools/gen-work-map.js — every job, shift and op on the in-game map
//
// The island draws the places it builds (the Glizzys-2-Go and dockhand
// stations, the lumber yard, the hunting grounds). Everything else you
// can work at lives in the game core, in js-snippets: where you go on
// shift, where each job signs you up, the stores you can hold up, the
// supply spots, the jail and the impound lots. This reads them straight
// from those modules and writes world-map/html/work.js, a layer the map
// draws on top of itself, so the map can never disagree with the game.
//
//   node tools/gen-work-map.js          (npm run gen:work-map)
//
// work.js is a separate file on purpose: tools/sync-from-island.js
// replaces index.html with the island's, and puts the one <script> tag
// for this layer back each time (addWorkLayer below).
// ============================================================

const fs = require("fs");
const path = require("path");

const REPO = path.join(__dirname, "..");
const js = (m) => require(path.join(REPO, "js-snippets", m));
const OUT = path.join(REPO, "world-map", "html", "work.js");
const TAG = '<script src="work.js"></script>';

// What each kind looks like, and the line it gets in the legend.
const KINDS = {
    shift:    { badge: "★", fill: "#1d3a6e", ink: "#f2c230", legend: "Go on shift (Sheriff, EMS): /duty, callsign" },
    hospital: { badge: "H", fill: "#ffffff", ink: "#c0392b", legend: "Hospital (EMS work, respawn)" },
    job:      { badge: "J", fill: "#0f766e", ink: "#ffffff", legend: "Job sign-up / clock-in" },
    store:    { badge: "$", fill: "#7e22ce", ink: "#ffffff", legend: "Store: shop, or /rob (op)" },
    supply:   { badge: "D", fill: "#3f6212", ink: "#d9f99d", legend: "Supply spot: /harvest (op)" },
    jail:     { badge: "⛓", fill: "#111827", ink: "#e5e7eb", legend: "Jail (police)" },
    impound:  { badge: "I", fill: "#4b5563", ink: "#ffffff", legend: "Impound lot (police, tow)" },
};

function collect() {
    const { JOBS } = js("jobs.js");
    const { DEPARTMENTS } = js("shifts.js");
    const { SHOPS } = js("shops.js");
    const { HOSPITALS } = js("medical.js");
    const { LOTS } = js("impound.js");
    const { JAIL } = js("police.js");
    const { SUPPLY_SPOTS, DRUGS } = js("drugs.js");
    const { YARD } = js("lumbermill.js");
    const out = [];
    const add = (kind, label, pos, detail) => out.push({ kind, label, detail, x: pos.x, y: pos.y });

    // Jobs with a station: departments run shifts (callsigns), the rest clock in.
    for (const [name, job] of Object.entries(JOBS)) {
        for (const pos of Object.values(job.stations || {})) {
            const pay = job.goldPerHour ? `${job.goldPerHour} gold/hr` : job.goldPerPaycheck ? `${job.goldPerPaycheck} gold a paycheck` : "";
            const grades = job.grades.map((g) => g.label).join(" → ");
            if (DEPARTMENTS[name]) add("shift", job.label, pos, `Go on shift: /duty (callsign ${DEPARTMENTS[name].prefix}-#). ${grades}. ${pay}`);
            else add("job", job.label, pos, `${job.openHire ? "/apply " + name : "Hired by staff"}, then /duty. ${grades}. ${pay}`);
        }
    }
    const lumber = JOBS.lumbermill;
    add("job", lumber.label, YARD.office, `/apply lumbermill, then /duty. ${lumber.goldPerHour} gold/hr; /fell, /mill at the saw, /sellplanks here`);

    for (const list of Object.values(HOSPITALS)) for (const h of list) add("hospital", h.label, h.pos, "EMS revive work; where you wake up");
    for (const s of Object.values(SHOPS)) add("store", s.label, s.pos, "Shop here. Holding it up: /rob (needs police on duty)");
    for (const s of SUPPLY_SPOTS) {
        const product = Object.values(DRUGS).find((d) => d.raw === s.raw);
        add("supply", s.label, s.pos, `/harvest ${s.raw}${product ? ` → /process into ${product.label} at your crew base, then /deal` : ""}`);
    }
    add("jail", "County Jail", JAIL.cell, "Where /jail sends people");
    for (const l of LOTS) add("impound", l.label, l.pos, "Towed cars; pay the fee to get yours back");
    return out;
}

// The browser half: draws the markers through the map's own gameToMap, keeps them a
// steady size on screen as you zoom, and adds their lines to the legend.
function layerScript(spots) {
    return `// world-map/html/work.js — generated by tools/gen-work-map.js from js-snippets. Don't edit by hand.
// Every job, shift and op the game core knows, drawn on the in-game map.
(function () {
  const KINDS = ${JSON.stringify(KINDS)};
  const SPOTS = ${JSON.stringify(spots)};
  const NS = "http://www.w3.org/2000/svg";
  const svg = document.getElementById("island");
  if (!svg || !window.gameToMap) return;
  const layer = document.createElementNS(NS, "g");
  layer.setAttribute("id", "work");
  const anchor = document.getElementById("waypoint");
  svg.insertBefore(layer, anchor && anchor.parentNode === svg ? anchor : null);   // under you and the waypoint

  const badge = (k, size) => {
    const g = document.createElementNS(NS, "g");
    g.innerHTML = '<rect x="-9" y="-9" width="18" height="18" rx="4" fill="' + k.fill + '" stroke="#fff" stroke-width="1.6"/>' +
      '<text y="4.5" text-anchor="middle" font-family="Arial, sans-serif" font-weight="700" font-size="' + (size || 12) + '" fill="' + k.ink + '">' + k.badge + "</text>";
    return g;
  };
  const marks = SPOTS.map((s) => {
    const m = window.gameToMap(s.x, s.y), g = badge(KINDS[s.kind]);
    g.setAttribute("class", "work-mark work-" + s.kind);
    const t = document.createElementNS(NS, "title");
    t.textContent = s.label + (m.off ? " (off the drawn streets)" : "") + "\\n" + s.detail;
    g.appendChild(t);
    layer.appendChild(g);
    return { g, x: m.x, y: m.y };
  });
  const W = 4660;
  // Markers keep a steady size on screen, so which ones overlap depends on the zoom. Each time
  // the view changes, markers closer than one badge apart are gathered into a cluster and laid
  // out side by side around the cluster's centre, so every one can be seen and hovered.
  const place = () => {
    const vb = (svg.getAttribute("viewBox") || "0 0 " + W).split(/\s+/).map(Number);
    const k = 2.2 / Math.pow(W / (vb[2] || W), 0.75);   // about 13 px on screen for the whole island, growing a little as you zoom
    const size = 18 * k, gap = size * 1.1;              // a badge is 18 units across before scaling
    const left = marks.slice(), clusters = [];
    while (left.length) {
      const c = [left.shift()];
      for (let grown = true; grown;) {                   // pull in anything touching any member
        grown = false;
        for (let i = left.length - 1; i >= 0; i--)
          if (c.some((m) => Math.abs(m.x - left[i].x) < gap && Math.abs(m.y - left[i].y) < gap)) { c.push(left.splice(i, 1)[0]); grown = true; }
      }
      clusters.push(c);
    }
    for (const c of clusters) {
      const cx = c.reduce((a, m) => a + m.x, 0) / c.length, cy = c.reduce((a, m) => a + m.y, 0) / c.length;
      c.sort((a, b) => a.x - b.x);
      c.forEach((m, i) => {
        const x = c.length === 1 ? m.x : cx + (i - (c.length - 1) / 2) * gap, y = c.length === 1 ? m.y : cy;
        m.g.setAttribute("transform", "translate(" + x + " " + y + ") scale(" + k + ")");
      });
    }
  };
  place();
  new MutationObserver(place).observe(svg, { attributes: true, attributeFilter: ["viewBox"] });

  // legend lines for the kinds on the map
  const ul = document.querySelector(".legend ul");
  if (ul) for (const k of Object.values(KINDS)) {
    const li = document.createElement("li");
    li.innerHTML = '<svg class="sw" viewBox="0 0 52 34"><rect width="52" height="34" fill="#9aa36f"/>' +
      '<g transform="translate(26 17) scale(1.5)">' + badge(k, 12).innerHTML + "</g></svg>" + k.legend;
    ul.appendChild(li);
  }
})();
`;
}

// Put the layer's <script> tag on the map page (idempotent). Used here and by sync-from-island.
function addWorkLayer(html) {
    if (html.includes(TAG)) return html;
    return html.replace("</body>", `${TAG}\n</body>`);
}

if (require.main === module) {
    const spots = collect();
    fs.writeFileSync(OUT, layerScript(spots));
    const page = path.join(REPO, "world-map", "html", "index.html");
    fs.writeFileSync(page, addWorkLayer(fs.readFileSync(page, "utf8")));
    const by = spots.reduce((a, s) => ((a[s.kind] = (a[s.kind] || 0) + 1), a), {});
    console.log(`wrote world-map/html/work.js: ${spots.length} spots (${Object.entries(by).map(([k, n]) => `${n} ${k}`).join(", ")})`);
}

module.exports = { collect, layerScript, addWorkLayer, KINDS, TAG };
